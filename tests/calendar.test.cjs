const {readFileSync} = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = readFileSync(require('node:path').join(__dirname, '../web/calendar.js'), 'utf8');
const at = vm.runInNewContext(source + '; StoryCalendar.at;');
function state(iso) { return at(new Date(iso), '2024-11-25', '2026-11-25'); }
assert.equal(state('2026-10-30T05:00:00Z').elapsed, 704);
assert.equal(state('2026-10-30T05:00:00Z').remaining, 26);
assert.equal(state('2026-10-29T16:59:59Z').elapsed, 703);
assert.equal(state('2026-10-29T17:00:00Z').elapsed, 704);
assert.equal(state('2026-10-29T17:00:00Z').today, '2026-10-30');
assert.equal(state('2024-11-24T17:00:00Z').elapsed, 0);
assert.equal(state('2024-11-23T17:00:00Z').elapsed, 0);
assert.equal(state('2026-11-24T17:00:00Z').elapsed, 730);
assert.equal(state('2026-11-24T17:00:00Z').remaining, 0);
assert.match(state('2026-11-24T17:00:00Z').status, /Hôm nay/);
assert.equal(state('2026-11-25T17:00:00Z').elapsed, 731);
assert.match(state('2026-11-25T17:00:00Z').status, /Mốc hai năm/);
assert.equal(at(new Date('2024-02-29T17:00:00Z'), '2024-02-28', '2026-02-28').elapsed, 2);
console.log('Calendar: current day, Vietnam midnight, anniversary, post-anniversary and leap day passed.');
